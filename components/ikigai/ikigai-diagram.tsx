"use client"

import { useMemo } from "react"
import { cn } from "@/lib/utils"
import { DIMENSIONS } from "./content"
import { buildScreenSvg, type DiagramData } from "./diagram/svg"

interface IkigaiDiagramProps {
  data: DiagramData
  variant: "full" | "compact"
  label: string
  className?: string
}

export function IkigaiDiagram({ data, variant, label, className }: IkigaiDiagramProps) {
  const { svg } = useMemo(() => buildScreenSvg(data, variant), [data, variant])
  const description = DIMENSIONS.map((d) => {
    const words = data.keywords[d.id]
    return `${d.name}: ${words.length ? words.join(", ") : "sin palabras clave"}`
  }).join(". ")

  return (
    <figure className={cn("w-full", className)}>
      <div
        role="img"
        aria-label={`${label}. ${description}. Propósito: ${data.hypothesis || "sin redactar"}.`}
        className="aspect-square w-full"
        // Markup is generated by buildScreenSvg, which XML-escapes every user string.
        dangerouslySetInnerHTML={{ __html: svg }}
      />
    </figure>
  )
}

export function useTruncation(data: DiagramData) {
  return useMemo(() => buildScreenSvg(data, "full").truncated, [data])
}
